// Generates lib/extensions/registry.generated.ts from extensions/*/manifest.json.
// Runs automatically before dev, build, test and typecheck (see package.json);
// run it by hand with `npm run extensions`. The output is not committed, so a
// new extension changes nothing outside its own folder.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ManifestSchema, RESERVED_SLUGS, SLUG } from "@/lib/extensions/manifest";

const root = process.cwd();
const dir = path.join(root, "extensions");
const out = path.join(root, "lib", "extensions", "registry.generated.ts");

const problems: string[] = [];
const entries: { slug: string }[] = [];

const folders = existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : [];
for (const slug of folders) {
  const where = `extensions/${slug}`;
  if (!SLUG.test(slug)) { problems.push(`${where}: folder name must be lowercase words joined by hyphens.`); continue; }
  if (RESERVED_SLUGS.includes(slug)) { problems.push(`${where}: "${slug}" is already used by the app; pick another name.`); continue; }
  const manifestPath = path.join(dir, slug, "manifest.json");
  if (!existsSync(manifestPath)) { problems.push(`${where}: missing manifest.json.`); continue; }
  let json: unknown;
  try { json = JSON.parse(readFileSync(manifestPath, "utf8")); } catch (e) { problems.push(`${where}/manifest.json is not valid JSON: ${(e as Error).message}`); continue; }
  const parsed = ManifestSchema.safeParse(json);
  if (!parsed.success) { problems.push(`${where}/manifest.json: ${parsed.error.issues.map((i) => `${i.path.join(".") || "(root)"} ${i.message}`).join("; ")}`); continue; }
  if (!existsSync(path.join(dir, slug, "index.tsx"))) { problems.push(`${where}: missing index.tsx (the view, as its default export).`); continue; }
  entries.push({ slug });
}

const lines = [
  "// Generated by scripts/gen-extensions.ts from extensions/*/manifest.json. Do not edit; not committed.",
  'import type { ExtensionManifest } from "./manifest";',
  'import type { ComponentType } from "react";',
  ...entries.flatMap((e, i) => [
    `import manifest${i} from "@/extensions/${e.slug}/manifest.json";`,
    `import View${i} from "@/extensions/${e.slug}";`,
  ]),
  "",
  "export const GENERATED: { slug: string; manifest: ExtensionManifest; Component: ComponentType<never> }[] = [",
  ...entries.map((e, i) => `  { slug: ${JSON.stringify(e.slug)}, manifest: manifest${i} as ExtensionManifest, Component: View${i} },`),
  "];",
  "",
];
const text = lines.join("\n");
if (!existsSync(out) || readFileSync(out, "utf8") !== text) writeFileSync(out, text);

for (const p of problems) console.warn(`⚠ Extension skipped: ${p}`);
console.log(`Extensions: ${entries.map((e) => e.slug).join(", ") || "none"}`);
